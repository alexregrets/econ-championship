def draw_defence(
    round_id: int,
    method: Method,
    team_ids: Sequence[str],
    *,
    attempt: int = 0,
) -> DefenceDraw:
    """Разыграть команду, роль и вопрос для микрозащиты после раунда.

    Parameters
    ----------
    round_id:
        Зерно жеребьёвки — вместе с ``attempt`` даёт воспроизводимый розыгрыш.
    method:
        Метод раунда; из его банка берётся вопрос.
    team_ids:
        Команды, подавшие решение в раунде. Сортируются перед розыгрышем,
        чтобы порядок из базы не менял результат.
    attempt:
        Номер перетяжки. Нулевая — основная; преподаватель может вытянуть
        вторую (команда не явилась), и она тоже воспроизводима.

    Raises
    ------
    ValueError
        Нет команд, или под метод нет вопросов.
    """
    if not team_ids:
        raise ValueError("некого спрашивать: в раунде нет команд с решением")
    questions = QUESTION_BANK.get(method)
    if not questions:
        raise ValueError(f"под метод {method.value} банка вопросов нет")

    rng = random.Random(f"defence:{round_id}:{attempt}")
    team_id = rng.choice(sorted(team_ids))
    role = rng.choice(list(Role))
    question = rng.choice(questions)
    return DefenceDraw(team_id=team_id, role=role, question=question)
