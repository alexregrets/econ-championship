"""Устная микрозащита: случайная команда × роль × вопрос по методу раунда.

Третья линия защиты от «скинул всё в ИИ» (решение 08.09): ловушка в данных
бьёт деньгами, рубрика — баллом, а этот модуль — тем, что после раунда
кому-то придётся **сказать вслух**, что команда сделала и почему. Модель
может написать обоснование; ответить на вопрос преподавателя через десять
секунд после жеребьёвки может только тот, кто понял.

Механика намеренно дешёвая: одна команда, одна роль, один вопрос за раунд.
Не экзамен, а лотерея с ненулевой ценой билета — ожидаемая стоимость
непонимания положительна для каждой команды, и этого достаточно.

Жеребьёвка детерминирована от ``round_id`` и списка команд: преподаватель
может нажать кнопку дважды и получить то же имя, иначе «перетяни, пока не
выпадет удобная» станет привычкой. Своё ``random.Random(seed)``, не
модульный ``random`` — по той же причине, что в ``core/dataset``.

Вопросы — по методу раунда и **про его ловушку**, а не по учебнику вообще:
«почему сквозная регрессия здесь врёт и в какую сторону» отделяет тех, кто
считал, от тех, кто вставил. У каждого вопроса есть ``expected`` — что
должно прозвучать в ответе; это подсказка преподавателю, студент её не
видит.

Как и весь ``core``: стандартная библиотека, без I/O.
"""

from __future__ import annotations

import random
from collections.abc import Sequence
from dataclasses import dataclass

from db.enums import Method, Role

__all__ = ["DefenceDraw", "DefenceQuestion", "QUESTION_BANK", "draw_defence"]


@dataclass(frozen=True)
class DefenceQuestion:
    """Вопрос микрозащиты и то, что должно прозвучать в ответе."""

    text: str
    expected: str


@dataclass(frozen=True)
class DefenceDraw:
    """Результат жеребьёвки: кого спрашиваем и о чём."""

    team_id: str
    role: Role
    question: DefenceQuestion


# Общие вопросы — годятся для любого метода: про связь оценки с решением.
_COMMON: tuple[DefenceQuestion, ...] = (
    DefenceQuestion(
        text=(
            "Назовите оценку наклона спроса, которую вы получили, и объясните, "
            "как из неё получился ваш объём."
        ),
        expected=(
            "Число наклона; условие первого порядка (A_i − c − 2·b·q = 0) или "
            "формула лучшего ответа; ожидание выпуска соперников, от которого "
            "считали остаточный спрос."
        ),
    ),
    DefenceQuestion(
        text=(
            "Какую цену вы ожидали увидеть после закрытия раунда и почему? "
            "Если фактическая отличается — за счёт чего?"
        ),
        expected=(
            "Ожидаемая цена = c + b·q при истинном наклоне, либо из своей "
            "модели; разница — ошибка в наклоне или в ожидании соперников."
        ),
    ),
    DefenceQuestion(
        text=(
            "Если бы остальные фирмы выпустили вдвое больше, чем вы ожидали, "
            "как изменился бы ваш оптимальный объём и почему?"
        ),
        expected=(
            "Остаточный спрос сдвинулся бы вниз, лучший ответ упал бы "
            "пропорционально (b·Q_−i входит в A_i); стратегическая замена."
        ),
    ),
)

