"""Рубрики обоснований по методу раунда — капканы против «скинул в ИИ».

Рубрика — вторая линия защиты после ловушки в данных (`core/cases`) и рядом
с детектором «кто попался» (`core/trap`). Логика та же, что в решении
08.09: не запрещать ИИ и не ловить «текст робота», а сделать так, чтобы
общий ответ — правильный по учебнику и пустой по существу — стоил баллов.

Как это устроено. Общая генерация («оценили спрос МНК, наклон отрицательный,
выбрали оптимальный объём») закрывает в этих рубриках ни один критерий,
потому что каждый требует одно из трёх:

* **число из данных** — оценка наклона, ожидаемая цена, статистика теста.
  Число нельзя сгенерировать, не прогнав регрессию на этом датасете;
* **признание ловушки** — что именно в данных этого раунда ломает наивную
  оценку и в какую сторону. Тот, кто скинул CSV в чат без чтения брифинга,
  ловушку не назовёт, потому что модель её не искала;
* **связь с решением** — как из оценки получился именно этот объём, с
  учётом выпуска соперников. Разрыв «сказал одно — подал другое» потом
  видит панель разбора.

Грейдер (`core/rubric_grader`) возвращает по критерию «да/нет» и цитату:
преподаватель видит, **чем** критерий закрыт, и может не поверить.

Веса внутри метода в сумме дают единицу — так балл рубрики читается как
доля. Это проверяется тестом, а не арифметикой на глаз.
"""

