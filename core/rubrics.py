def rubric_for_method(method: Method) -> list[RubricCriterion]:
    """Рубрика по умолчанию для метода раунда.

    Raises
    ------
    NotImplementedError
        Под метод рубрики нет — так же громко, как `core.cases.build_case`:
        раунд без рубрики оценивать нельзя, и выдумывать её на ходу тоже.
    """
    rubric = DEFAULT_RUBRICS.get(method)
    if rubric is None:
        raise NotImplementedError(
            f"под метод {method.value} рубрики ещё нет. Есть: "
            f"{', '.join(m.value for m in DEFAULT_RUBRICS)}"
        )
    return list(rubric)
