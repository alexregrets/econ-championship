"""Генератор рыночной истории раунда — данные, которые видит команда.

Команда не знает `a`, `b` и своих издержек. Единственный способ их увидеть —
оценить по этой истории. Отсюда два требования, определяющие весь модуль.

**Воспроизводимость.** Одно зерно даёт один и тот же датасет, всегда. Без
этого невозможен разбор после раунда: препод не сможет показать те же числа,
которые видела команда. Поэтому здесь свой :class:`random.Random`, а не
глобальный модуль ``random`` — иначе результат зависел бы от того, что процесс
делал до вызова, и ломался бы незаметно.

**Оценимость.** По этим данным МНК обязан восстанавливать заложенные параметры
спроса. Датасет, из которого не выводится правда, — молчаливый провал: студент
честно применит метод, получит мусор и не поймёт, чья это вина. Свойство
закреплено тестами против настоящего ``statsmodels``.

Как и остальной ``core``: только стандартная библиотека, никакого I/O и
никаких обращений к БД. Научный стек нужен тестам, а не расчёту.

Об экзогенности
---------------
Объём здесь варьируется экзогенно: считается, что в исторические периоды выпуск
двигали причины со стороны предложения (аварии, ремонты, ввод мощностей), а не
одновременный выбор фирм. В реальности `P` и `Q` определяются совместно, и
регрессия цены на объём страдала бы от эндогенности.

Упрощение сознательное. Шесть методов курса Кудрявцева (см. :class:`db.enums.
Method`) заканчиваются панельными данными и инструментальных переменных не
включают, поэтому одновременность в турнир не заводится. Это выбор, а не
недосмотр: если курс дорастёт до IV, экзогенный сдвиг предложения здесь уже
есть и станет готовым инструментом.
"""

from __future__ import annotations

import random
from collections.abc import Mapping
from dataclasses import dataclass, field

from core.market_engine import MarketParameters

__all__ = ["Observation", "HistorySpec", "DEFAULT_SPEC", "generate_market_history"]

# Меньше этого числа точек регрессия перестаёт быть осмысленной: оценка наклона
# шумит сильнее, чем сам эффект, который студент должен увидеть.
MIN_PERIODS = 10


@dataclass(frozen=True)
class Observation:
    """Одно наблюдение рыночной истории — строка будущей выгрузки.

    Attributes
    ----------
    period:
        Номер периода, начиная с единицы.
    quantity:
        Суммарный выпуск рынка за период.
    price:
        Наблюдаемая цена.
    extras:
        Дополнительные столбцы кейса (режимные дамми, издержки, расходы на
        рекламу). Пусто у baseline-раунда; заполняется сценариями из
        ``CASES.md``.
    """

    period: int
    quantity: float
    price: float
    extras: Mapping[str, float] = field(default_factory=dict)


@dataclass(frozen=True)
class HistorySpec:
    """Настройки генерации.

    Attributes
    ----------
    periods:
        Сколько наблюдений выдать команде.
    seed:
        Зерно. Один и тот же кейс с одним зерном обязан давать один датасет.
    noise_sd:
        Стандартное отклонение шума **в единицах цены**, не в долях. Так его
        проще соотносить с уровнем цен кейса и с тем, насколько трудной должна
        быть оценка.
    quantity_spread:
        Разброс выпуска вокруг опорного значения, доля. ``0.3`` означает
        коридор ±30%. Чем он уже, тем хуже идентифицируется наклон: без
        вариации выпуска оценивать спрос не по чему.

    Raises
    ------
    ValueError
        При отрицательном шуме или неположительном разбросе.
    """

    periods: int = 30
    seed: int = 0
    noise_sd: float = 20.0
    quantity_spread: float = 0.30

    def __post_init__(self) -> None:
        if self.noise_sd < 0:
            raise ValueError(
                f"noise_sd должно быть неотрицательным, получено {self.noise_sd}"
            )
        if self.quantity_spread <= 0:
            raise ValueError(
                "quantity_spread должен быть положительным: без вариации выпуска "
                f"наклон спроса не идентифицируется, получено {self.quantity_spread}"
            )


# Настройки по умолчанию отдельной константой, а не вызовом в сигнатуре:
# HistorySpec заморожен, поэтому один общий экземпляр безопасен, а значение
# по умолчанию перестаёт быть вызовом функции при разборе модуля.
DEFAULT_SPEC = HistorySpec()


def generate_market_history(
    params: MarketParameters,
    *,
    reference_quantity: float,
    spec: HistorySpec = DEFAULT_SPEC,
) -> list[Observation]:
    """Сгенерировать историю наблюдений вокруг заданного рынка.

    Модель: ``P_t = a - b * Q_t + e_t``, где ``Q_t`` колеблется вокруг
    ``reference_quantity`` в коридоре ``quantity_spread``, а ``e_t`` —
    нормальный шум со средним ноль.

    Parameters
    ----------
    params:
        Истинные параметры рынка. Команде не показываются — их и предстоит
        оценить.
    reference_quantity:
        Опорный выпуск, вокруг которого гуляет история. Обычно равновесный
        выпуск кейса, чтобы наблюдения лежали в том же диапазоне, в котором
        команда потом принимает решение.
    spec:
        Настройки генерации.

    Returns
    -------
    list[Observation]
        Ровно ``spec.periods`` наблюдений, пронумерованных с единицы.

    Raises
    ------
    ValueError
        Если периодов меньше :data:`MIN_PERIODS` или опорный выпуск
        неположителен.
    """
    if spec.periods < MIN_PERIODS:
        raise ValueError(
            f"нужно минимум {MIN_PERIODS} наблюдений, чтобы регрессия имела "
            f"смысл, запрошено {spec.periods}"
        )
    if reference_quantity <= 0:
        raise ValueError(
            f"опорный выпуск должен быть положительным, получено {reference_quantity}"
        )

    rng = random.Random(spec.seed)
    history: list[Observation] = []

    for period in range(1, spec.periods + 1):
        shift = rng.uniform(-spec.quantity_spread, spec.quantity_spread)
        quantity = reference_quantity * (1.0 + shift)
        noise = rng.gauss(0.0, spec.noise_sd) if spec.noise_sd > 0 else 0.0
        price = params.a - params.b * quantity + noise

        # Отрицательная цена — не «плохое наблюдение», а сломанный кейс:
        # рынок настроен так, что шум уводит цену за ноль. Молча обрезать
        # нельзя, обрезка исказит оценку и студент этого не увидит.
        if price <= 0:
            raise ValueError(
                f"период {period}: цена ушла в {price:.2f}. Кейс настроен так, "
                f"что шум ({spec.noise_sd}) или разброс выпуска "
                f"({spec.quantity_spread}) выносят цену за ноль — уменьшите их "
                f"или поднимите точку насыщения спроса"
            )

        history.append(Observation(period=period, quantity=quantity, price=price))

    return history
