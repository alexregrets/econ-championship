"""Входная страница Streamlit-дашборда профессора.

Запуск::

    uv run streamlit run dashboard/app.py

Сами инструменты — на странице «Раунды» (dashboard/pages/01_rounds.py);
здесь только приветствие и краткая справка.
"""

from __future__ import annotations

import streamlit as st


def main() -> None:
    """Отрисовать домашнюю страницу с краткой справкой по дашборду."""
    st.set_page_config(page_title="Econ Championship — дашборд", page_icon="📈")
    st.title("Эконометрический турнир — дашборд профессора")
    st.markdown(
        "Управление раундами — на странице **Раунды** в меню слева:\n"
        "- создать и открыть раунд (сценарий «Нефть РФ 2013», парная регрессия), "
        "движок симметричный или асимметричный;\n"
        "- внести решения команд вручную (основной канал — Telegram-бот);\n"
        "- закрыть раунд и посмотреть сырой дамп результатов.\n\n"
        "Страница **Витрина** — публичный read-only взгляд для студентов: "
        "статус раунда, сценарий, прогресс команды; решения подаются только "
        "через Telegram-бота."
    )


main()
