"""Входная страница Streamlit-дашборда профессора.

Запуск::

    uv run streamlit run dashboard/app.py

Сами инструменты — на странице «Раунды» (dashboard/pages/01_rounds.py);
здесь только приветствие и краткая справка.
"""

from __future__ import annotations

import streamlit as st

from dashboard.auth import require_teacher


def main() -> None:
    """Отрисовать домашнюю страницу с краткой справкой по дашборду."""
    st.set_page_config(page_title="Econ Championship — дашборд", page_icon="📈")
    require_teacher()
    st.title("Эконометрический турнир — дашборд профессора")
    st.markdown(
        "### Как проходит раунд\n"
        "1. **Раунды → Новый раунд**: метод (он же тема недели), параметры рынка "
        "`a`, `b`, `c`. Форма скажет, каким выйдет равновесие при текущем числе "
        "команд, и предупредит, если рынок тесный или параметры повторяют прошлый "
        "раунд.\n"
        "2. Команды получают брифинг и данные в Telegram (`/brief`, `/data`) или на "
        "**Витрине**. В данных заложена закономерность под метод раунда — "
        "наивная оценка её не видит и теряет деньги.\n"
        "3. Команды считают и подают объём с обоснованием: `/submit <Q> <текст>`. "
        "Пока раунд открыт, можно переподать.\n"
        "4. **Закрыть раунд** — движок Курно считает цену и прибыли. Команды видят "
        "разбор в `/result`: что ждали, что получили, какой объём был лучшим.\n"
        "5. **Панель разбора** под результатами: во что верила каждая команда и "
        "кто попался на ловушку метода. **Микрозащита** — кнопка разыгрывает "
        "команду, роль и вопрос; ответ должен прозвучать вслух.\n"
        "6. **Оценить обоснования (Groq)** — рубрика метода с проверкой названных "
        "чисел против истины раунда. Балл — доля, цитаты — по критерию.\n\n"
        "Витрина открыта всем; эта страница и Раунды — по паролю из `.env`. "
        "Перед первым раундом: `uv run python -m devshell.seed` (команды и коды), "
        "`uv run python -m devshell.team_codes` (коды для `/join`)."
    )


main()
